"""Original background music, synthesised locally (no third-party rights).

It is a simple ambient pad, intentionally modest. If you place your own audio
files in assets/music/ they are preferred, but YOU must confirm their licence;
the project report flags them as 'user-supplied, rights unverified'.
"""
from __future__ import annotations

import random
import wave
from pathlib import Path

import numpy as np

SR = 44100
SEMI = 2 ** (1 / 12)
MOODS = {   # root Hz, chord progression (semitone offsets), seconds per chord, arpeggio, gain
    "calm":      dict(root=196.00, chords=[[0, 4, 7, 12], [-3, 4, 9, 12], [-5, 2, 7, 11], [-7, 0, 4, 9]], sec=7.0, arp=False),
    "uplifting": dict(root=220.00, chords=[[0, 4, 7, 12], [7, 11, 14, 19], [9, 12, 16, 21], [5, 9, 12, 17]], sec=5.0, arp=True),
    "cinematic": dict(root=146.83, chords=[[0, 7, 12, 15], [-4, 3, 8, 12], [-2, 5, 10, 14], [-7, 0, 7, 12]], sec=8.0, arp=False),
    "playful":   dict(root=261.63, chords=[[0, 4, 7, 11], [5, 9, 12, 16], [7, 11, 14, 17], [0, 4, 7, 12]], sec=4.0, arp=True),
    "tense":     dict(root=130.81, chords=[[0, 3, 7, 10], [-2, 3, 6, 10], [-4, 0, 3, 8], [-5, -2, 3, 7]], sec=6.0, arp=False),
}


def _tone(freq, t, detune=0.0):
    f = freq * (1 + detune)
    return (np.sin(2 * np.pi * f * t) + 0.35 * np.sin(2 * np.pi * 2 * f * t)
            + 0.12 * np.sin(2 * np.pi * 3 * f * t))


def synth_music(path, seconds: float, mood: str = "calm", seed: int = 0) -> str:
    cfg = MOODS.get(mood, MOODS["calm"])
    rng = random.Random(seed)
    n = int(seconds * SR)
    left, right = np.zeros(n), np.zeros(n)
    sec, over = cfg["sec"], 2.0
    k, start = 0, 0.0
    while start < seconds:
        chord = cfg["chords"][k % len(cfg["chords"])]
        length = sec + over
        i0, cnt = int(start * SR), int(length * SR)
        cnt = min(cnt, n - i0)
        if cnt <= 0:
            break
        t = np.arange(cnt) / SR
        env = np.minimum(1, t / over) * np.minimum(1, (length - t) / over)   # soft cross-fade
        env = env ** 1.5
        for semis in chord:
            f = cfg["root"] * SEMI ** semis
            lfo = 1 + 0.08 * np.sin(2 * np.pi * rng.uniform(0.05, 0.15) * t + rng.uniform(0, 6))
            left[i0:i0 + cnt] += env * lfo * _tone(f, t, -0.002) * 0.16
            right[i0:i0 + cnt] += env * lfo * _tone(f, t, +0.002) * 0.16
        sub = env * np.sin(2 * np.pi * cfg["root"] * SEMI ** (chord[0] - 12) * t) * 0.22
        left[i0:i0 + cnt] += sub
        right[i0:i0 + cnt] += sub
        if cfg["arp"]:
            step = 0.5
            for j, tt in enumerate(np.arange(0, sec, step)):
                f = cfg["root"] * SEMI ** (chord[j % len(chord)] + 12)
                a0 = int((start + tt) * SR)
                m = min(int(0.9 * SR), n - a0)
                if m <= 0:
                    continue
                tn = np.arange(m) / SR
                pluck = np.exp(-4.5 * tn) * np.sin(2 * np.pi * f * tn) * 0.09
                pan = 0.3 + 0.4 * ((j % 4) / 3)
                left[a0:a0 + m] += pluck * (1 - pan)
                right[a0:a0 + m] += pluck * pan
        k += 1
        start += sec
    fade = int(min(2.0, seconds / 4) * SR)
    ramp = np.linspace(0, 1, fade)
    for ch in (left, right):
        ch[:fade] *= ramp
        ch[-fade:] *= ramp[::-1]
    peak = max(np.abs(left).max(), np.abs(right).max(), 1e-9)
    stereo = np.stack([left, right], axis=1) / peak * 0.6
    pcm = (stereo * 32767).astype("<i2")
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), "wb") as w:
        w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes(pcm.tobytes())
    return str(path)


def choose_music(settings, mood: str, seconds: float, work_dir) -> tuple:
    """Return (path, info). Prefers user-supplied files, else synthesises."""
    lib = Path(settings.music_dir)
    if lib.is_dir():
        files = sorted(p for p in lib.iterdir() if p.suffix.lower() in (".mp3", ".wav", ".ogg", ".m4a"))
        mood_files = [p for p in files if mood in p.stem.lower()] or files
        if mood_files:
            pick = mood_files[0]
            return str(pick), {"source": "user-supplied", "file": pick.name, "mood": mood,
                               "rights": "UNVERIFIED: confirm you have commercial-use rights for this file."}
    out = Path(work_dir) / "music.wav"
    synth_music(out, seconds + 2, mood)
    return str(out), {"source": "synthesised", "mood": mood,
                      "rights": "Original audio generated by AUTO REEL AI; no third-party rights."}
