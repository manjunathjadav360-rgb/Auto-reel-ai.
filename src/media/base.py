"""Provider-neutral types for AUTO REEL AI media sourcing.

Every media provider (Pixabay today, others later) returns MediaAsset objects
and implements MediaProvider. Nothing outside src/media should import a
specific provider.
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import asdict, dataclass, field
from typing import Iterable, Optional


# ---------------------------------------------------------------- errors ----
class MediaError(Exception):
    """Base class for all media-layer errors."""


class MediaConfigError(MediaError):
    """Missing or invalid configuration (for example a missing API key)."""


class MediaAuthError(MediaError):
    """The provider rejected our credentials."""


class MediaProviderError(MediaError):
    """Network, server or response-format problem."""


class MediaDownloadError(MediaError):
    """A download was refused or failed validation."""


class MediaRateLimitError(MediaError):
    """The provider's rate limit was hit and retries were exhausted."""

    def __init__(self, message: str, retry_after: Optional[float] = None):
        super().__init__(message)
        self.retry_after = retry_after


# ----------------------------------------------------------------- asset ----
@dataclass
class MediaAsset:
    provider: str            # registry name, e.g. "pixabay"
    source_name: str         # display name, e.g. "Pixabay"
    source_url: str          # provider home page
    license_name: str
    license_url: str
    asset_id: str
    kind: str                # "video" | "image"
    page_url: str            # human-readable source page
    download_url: str
    width: int
    height: int
    creator: str = ""
    creator_url: str = ""
    tags: list = field(default_factory=list)
    duration: float = 0.0    # seconds, videos only
    thumbnail_url: str = ""
    local_path: Optional[str] = None
    # Provenance: everything from a media provider is stock material.
    # It is never labelled "AI-generated" by this project.
    origin: str = "stock"
    meta: dict = field(default_factory=dict)

    @property
    def orientation(self) -> str:
        if self.height > self.width:
            return "vertical"
        if self.height < self.width:
            return "horizontal"
        return "square"

    @property
    def is_vertical(self) -> bool:
        return self.orientation == "vertical"

    @property
    def needs_crop_for_9x16(self) -> bool:
        """True when the editor must crop/zoom this asset to fill 9:16."""
        return not self.is_vertical

    def attribution_line(self) -> str:
        label = "Video" if self.kind == "video" else "Image"
        who = f" by {self.creator}" if self.creator else ""
        return f"{label}{who} via {self.source_name}: {self.page_url}"

    def to_dict(self) -> dict:
        return asdict(self)


# -------------------------------------------------------------- provider ----
class MediaProvider(ABC):
    name: str = ""
    display_name: str = ""
    home_url: str = ""
    license_name: str = ""
    license_url: str = ""

    @classmethod
    @abstractmethod
    def from_env(cls, env, cache_dir) -> "MediaProvider":
        """Build the provider from environment variables (never from code)."""

    @abstractmethod
    def search_videos(self, query: str, **options) -> list:
        """Return MediaAsset objects (kind="video")."""

    @abstractmethod
    def search_images(self, query: str, **options) -> list:
        """Return MediaAsset objects (kind="image")."""

    @abstractmethod
    def download(self, asset: MediaAsset, dest_dir) -> MediaAsset:
        """Download to dest_dir, validate, set asset.local_path, return it."""


# --------------------------------------------------------------- credits ----
def unique_assets(assets: Iterable[MediaAsset]) -> list:
    seen, out = set(), []
    for a in assets:
        key = (a.provider, a.asset_id, a.kind)
        if key not in seen:
            seen.add(key)
            out.append(a)
    return out


def credits_text(assets: Iterable[MediaAsset]) -> str:
    """Full source/attribution block for the dashboard and publishing package."""
    assets = unique_assets(assets)
    if not assets:
        return ""
    sources = {}
    for a in assets:
        sources[a.source_name] = (a.source_url, a.license_name, a.license_url)
    head = []
    for name, (url, lic, lic_url) in sources.items():
        head.append(
            f"Stock media sourced from {name} ({url}), used under the "
            f"{lic} ({lic_url}). Not generated by AUTO REEL AI."
        )
    return "\n".join(head + [""] + [f"- {a.attribution_line()}" for a in assets])


def credits_short(assets: Iterable[MediaAsset]) -> str:
    """One line suitable for an Instagram caption (optional, but transparent)."""
    assets = unique_assets(assets)
    if not assets:
        return ""
    sources = sorted({a.source_name for a in assets})
    creators = sorted({a.creator for a in assets if a.creator})
    line = "Stock footage/images: " + ", ".join(sources)
    if creators:
        line += " (creators: " + ", ".join(creators[:6]) + ")"
    return line
